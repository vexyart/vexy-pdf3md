"""Publish completed artifacts, retaining existing files on conversion failure."""

import os
import shutil
from pathlib import Path

MARKER = ".vexy-pdf3md"


def publish(staged: Path, output: Path, media: Path | None, overwrite: bool) -> None:
    """Markdown is the commit point. Restore old media if publishing it fails."""
    destination = output.with_suffix("")
    backup = staged.parent / "previous-media"
    installed = False
    if media is not None:
        if destination.exists():
            if not overwrite or not (destination / MARKER).is_file():
                raise FileExistsError(
                    f"media directory already exists and is not replaceable: {destination}"
                )
            destination.rename(backup)
        try:
            (media / MARKER).write_text("Generated by vexy-pdf3md\n")
            media.rename(destination)
            installed = True
        except BaseException:
            if backup.exists():
                backup.rename(destination)
            raise
    try:
        if overwrite:
            os.replace(staged, output)
        else:
            os.link(staged, output)
            staged.unlink()
    except BaseException:
        if installed:
            shutil.rmtree(destination)
        if backup.exists():
            backup.rename(destination)
        raise
    if backup.exists():
        shutil.rmtree(backup)
